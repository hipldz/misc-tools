export function t(key, vars = {}) {
  const value = messages[state.language]?.[key] || messages.en[key] || key;
  return value.replace(/\{(\w+)\}/g, (_, name) => String(vars[name] ?? ""));
}
export function relativeTime(value) {
  if (!value) return t("never");
  const seconds = Math.max(
    0,
    Math.floor((Date.now() - Date.parse(value)) / 1000),
  );
  if (seconds < 10) return t("justNow");
  if (seconds < 60) return t("secondsAgo", { count: seconds });
  if (seconds < 3600)
    return t("minutesAgo", { count: Math.floor(seconds / 60) });
  if (seconds < 86400)
    return t("hoursAgo", { count: Math.floor(seconds / 3600) });
  return new Date(value).toLocaleString(
    state.language === "zh" ? "zh-CN" : "en",
  );
}
